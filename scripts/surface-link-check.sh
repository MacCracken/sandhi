#!/bin/bash
# Whole-surface link check: every sandhi function, public and private, linked at
# once under CYRIUS_DCE=1.
#
# programs/smoke.cyr references a single sandhi fn, so its clean link proves
# little about the rest of the surface: DCE drops everything smoke does not
# reach, and a function whose body calls an undefined stub only fails the link
# when something reaches it. This takes `&fn` of all of them, so the toolchain's
# refusing linker ("reachable undefined function") checks every one.
#
#   1. The surface is every `fn` defined at the top level of the [lib].modules
#      files. None is defined inside an #if / #ifdef / #ifndef block today, so
#      all of them are compiled on every target. The script refuses to run if
#      one ever is, rather than reference a fn this target does not compile:
#      teach it the block's condition then. (CYRIUS_DCE_VERBOSE cannot stand in
#      for this: it lists only fns DCE removed, and every fn reachable from an
#      address-taken one, such as a pooled worker, counts as live.)
#   2. A probe taking `&fn` of each one must link.
#   3. Negative control: the same probe plus a call to a function that does not
#      exist must be refused as a reachable undefined function. If it is not,
#      step 2 proved nothing.
#
# Usage: scripts/surface-link-check.sh   (from anywhere; generated files go in
# build/surface/, which is gitignored). Exits non-zero on any failure.
# CHANGELOG [1.11.2]; the one-off version of this probe is in CHANGELOG [1.10.0].

set -euo pipefail
cd "$(dirname "$0")/.."

OUT=build/surface
mkdir -p "$OUT"

# The [lib].modules list, in manifest order.
mapfile -t MODS < <(awk '
    /^\[lib\][[:space:]]*$/ { inlib = 1; next }
    /^\[/                   { inlib = 0 }
    inlib && /"src\//       { gsub(/[",[:space:]]/, ""); print }
' cyrius.cyml)
if [ "${#MODS[@]}" -eq 0 ]; then
    echo "surface: no [lib].modules found in cyrius.cyml" >&2
    exit 1
fi

INCLUDES=""
for m in "${MODS[@]}"; do
    INCLUDES+="include \"$m\""$'\n'
done

# 1. The surface: every top-level fn, refusing any defined under an #if.
GUARDED=$(awk '
    FNR == 1 { depth = 0 }
    /^[[:space:]]*#if/    { depth++; next }
    /^[[:space:]]*#endif/ { if (depth > 0) depth--; next }
    /^fn [A-Za-z_]/ && depth > 0 { name = $2; sub(/\(.*/, "", name); print FILENAME ": " name }
' "${MODS[@]}")
if [ -n "$GUARDED" ]; then
    echo "surface: these fns are defined inside an #if block, so not every target" >&2
    echo "         compiles them; teach scripts/surface-link-check.sh the condition:" >&2
    echo "$GUARDED" >&2
    exit 1
fi
grep -hoE '^fn [A-Za-z_][A-Za-z0-9_]*' "${MODS[@]}" \
    | awk '{ print $2 }' | sort -u > "$OUT/fns.txt"
N=$(wc -l < "$OUT/fns.txt")
if [ "$N" -lt 100 ]; then
    echo "surface: only $N fns found in [lib].modules; the scan is broken" >&2
    exit 1
fi

# 2 and 3. The probe, in chunks of 100 references per fn.
gen_probe() {   # $1 = output file, $2 = extra statement for main (or empty)
    {
        echo "# Generated by scripts/surface-link-check.sh. Do not edit."
        printf '%s' "$INCLUDES"
        echo "var _surface_sink = 0;"
        awk '
            NR % 100 == 1 { if (NR > 1) { print "    return 0;"; print "}" }
                            printf "fn _surface_%d() {\n", int((NR - 1) / 100) }
            { printf "    _surface_sink = &%s;\n", $1 }
            END { if (NR > 0) { print "    return 0;"; print "}" } }
        ' "$OUT/fns.txt"
        echo "fn main() {"
        awk 'NR % 100 == 1 { printf "    _surface_%d();\n", int((NR - 1) / 100) }' "$OUT/fns.txt"
        if [ -n "$2" ]; then echo "    $2"; fi
        echo "    return 0;"
        echo "}"
        echo "var r = main();"
        echo "sys_exit(r);"
    } > "$1"
}

gen_probe "$OUT/_surface_probe.cyr" ""
if ! CYRIUS_DCE=1 cyrius build "$OUT/_surface_probe.cyr" "$OUT/_surface_probe" \
        > "$OUT/probe.log" 2>&1; then
    cat "$OUT/probe.log" >&2
    echo "surface: FAIL: the $N-fn surface does not link (see above)" >&2
    exit 1
fi

gen_probe "$OUT/_surface_control.cyr" "_sandhi_surface_control_no_such_fn();"
if CYRIUS_DCE=1 cyrius build "$OUT/_surface_control.cyr" "$OUT/_surface_control" \
        > "$OUT/control.log" 2>&1; then
    echo "surface: FAIL: the negative control linked; an undefined reachable fn" >&2
    echo "         is not refused, so the surface link proves nothing" >&2
    exit 1
fi
if ! grep -q "_sandhi_surface_control_no_such_fn" "$OUT/control.log"; then
    cat "$OUT/control.log" >&2
    echo "surface: FAIL: the negative control failed, but not on its undefined fn" >&2
    exit 1
fi

echo "surface: all $N sandhi fns (public and private) link under CYRIUS_DCE=1"
echo "surface: negative control refused, as it must be"
